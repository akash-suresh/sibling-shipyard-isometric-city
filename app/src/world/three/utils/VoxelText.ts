export interface VoxelTextOptions {
  letterSpacing?: number;
}

/**
 * Creates a 3D pixel/voxel representation of the provided text.
 *
 * @param text The string to render in voxel form.
 * @param material The Three.js material to apply to each voxel cube.
 * @param options Optional configuration like custom letter spacing.
 * @returns A THREE.Group containing all the voxel meshes positioned on X and Y axes.
 */
export function createVoxelText(
  text: string,
  material: THREE.Material,
  options?: VoxelTextOptions
): THREE.Group {
  const group = new THREE.Group();
  const letterSpacing = options?.letterSpacing ?? 1;

  let cursorX = 0;
  const upperText = text.toUpperCase();

  for (let i = 0; i < upperText.length; i++) {
    const char = upperText[i];
    const grid = VOXEL_FONT[char] ?? VOXEL_FONT[' '];
    const gridHeight = grid.length;
    const gridWidth = grid[0]?.length ?? 4;

    for (let r = 0; r < gridHeight; r++) {
      const row = grid[r];
      const y = gridHeight - 1 - r;

      for (let c = 0; c < row.length; c++) {
        if (row[c] === 1) {
          const geo = new THREE.BoxGeometry(1, 1, 1);
          const mesh = new THREE.Mesh(geo, material);
          mesh.position.set(cursorX + c, y, 0);
          group.add(mesh);
        }
      }
    }

    cursorX += gridWidth + letterSpacing;
  }

  return group;
}
